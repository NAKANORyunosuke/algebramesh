//! The names of the types in operation signatures (ADR 0022). A result can be
//! passed as an argument of another operation only where the two names agree.
//!
//! The names of results are the `type` keys of their JSON values.

/// A polynomial ring: coefficient domain, variables and monomial order
/// (`RingSpec`).
pub const RING: &str = "ring";
/// A polynomial in the ring given beside it (`PolynomialData`).
pub const POLYNOMIAL: &str = "polynomial";
/// The value of `polynomial.factor` ([`crate::FactorResult`]).
pub const FACTORIZATION: &str = "factorization";
/// A rectangular integer matrix (`IntegerMatrix`).
pub const INTEGER_MATRIX: &str = "integer_matrix";
/// A vector of rational numbers.
pub const RATIONAL_VECTOR: &str = "rational_vector";
/// A vector of integers.
pub const INTEGER_VECTOR: &str = "integer_vector";
/// A non-negative integer.
pub const NONNEGATIVE_INTEGER: &str = "nonnegative_integer";
/// A list of elements of the Weyl algebra, each as its terms (`WeylTermData`).
pub const WEYL_OPERATOR_LIST: &str = "weyl_operator_list";
/// The value of `gkz.generate`.
pub const GKZ_SYSTEM: &str = "gkz_system";
/// The value of `gkz.indicial`.
pub const GKZ_INDICIAL: &str = "gkz_indicial";
/// The value of `gkz.series`.
pub const GKZ_SERIES: &str = "gkz_series";
/// ZZ or QQ.
pub const COEFFICIENT_DOMAIN: &str = "coefficient_domain";
/// A dense matrix over the domain given beside it (`RationalMatrix`).
pub const MATRIX: &str = "matrix";
/// `include` or `none`: whether a certificate comes with the value.
pub const CERTIFICATE_REQUEST: &str = "certificate_request";
/// The value of `matrix.rank`.
pub const MATRIX_RANK: &str = "matrix_rank";
/// The value of `matrix.kernel`.
pub const MATRIX_KERNEL: &str = "matrix_kernel";
/// The value of `matrix.solve`.
pub const MATRIX_SOLUTION: &str = "matrix_solution";
/// The value of `matrix.hermite_normal_form`.
pub const HERMITE_NORMAL_FORM: &str = "hermite_normal_form";
/// The value of `matrix.smith_normal_form`.
pub const SMITH_NORMAL_FORM: &str = "smith_normal_form";
/// An ideal given by generators in the ring given with it (`IdealData`).
pub const IDEAL: &str = "ideal";
/// `representation`, `s_pairs` or `none`: which certificate comes with a
/// Groebner basis.
pub const IDEAL_CERTIFICATE_REQUEST: &str = "ideal_certificate_request";
/// The value of `ideal.groebner_basis`.
pub const GROEBNER_BASIS: &str = "groebner_basis";
/// The value of `ideal.normal_form`.
pub const NORMAL_FORM: &str = "normal_form";
/// The value of `ideal.membership`.
pub const IDEAL_MEMBERSHIP: &str = "ideal_membership";
/// A submodule of a free module, generated by the columns of a polynomial
/// matrix (`SubmoduleData`).
pub const SUBMODULE: &str = "submodule";
/// The value of `module.syzygies`.
pub const SYZYGIES: &str = "syzygies";
/// The value of `complex.free_resolution`.
pub const FREE_RESOLUTION: &str = "free_resolution";
/// The value of `ideal.hilbert_series`.
pub const HILBERT_SERIES: &str = "hilbert_series";
/// A boolean.
pub const BOOLEAN: &str = "boolean";
/// A simplicial complex by its facets (`SimplicialComplexData`).
pub const SIMPLICIAL_COMPLEX: &str = "simplicial_complex";
/// The value of `simplicial.homology`.
pub const SIMPLICIAL_HOMOLOGY: &str = "simplicial_homology";

