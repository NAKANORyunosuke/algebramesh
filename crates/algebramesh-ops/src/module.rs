//! Free modules over QQ[x_1, ..., x_n] (A4, Issues #97, #98, ADR 0027):
//! `module.syzygies`, `complex.free_resolution` and `ideal.hilbert_series`.
//! A CAS computes the values; `algebramesh-verify` checks what it can.
//!
//! A submodule of the free module R^m is given by generators, the columns
//! of an m x s matrix F. The value of `module.syzygies` is an s x r matrix
//! S whose columns generate the module of syzygies {a in R^s : F a = 0}.
//!
//! The value of `complex.free_resolution` is a free resolution
//! F_0 = R <- F_1 <- ... <- F_k of R/I for an ideal I, given by its
//! differentials d_1 (1 x n_1), ..., d_k (n_{k-1} x n_k); the image of d_1 is
//! I. When every generator of I is homogeneous (in the grading with each
//! variable of degree 1), the value also gives the degree of each basis
//! element of each F_i, and, when no differential has a nonzero constant
//! entry, the graded Betti numbers of R/I counted from those degrees. Its
//! certificate is two matrices: C (s x n_1) with d_1 = F C and N (n_1 x s)
//! with F = d_1 N, for the s generators F of I.
//!
//! The value of `ideal.hilbert_series` is the Hilbert series of R/I for a
//! homogeneous I, as a polynomial P(t) with integer coefficients and an
//! exponent d with H(t) = P(t) / (1 - t)^d, in lowest terms. On request it
//! also gives the graded Betti numbers of R/I from the same backend, against
//! which the checker compares the series.

